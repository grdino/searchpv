    CONSTRAINT lstng_search_attribute_furnished_ck
        CHECK (furnished_cd IS NULL OR furnished_cd IN
            ('FURNISHED', 'PARTIALLY_FURNISHED', 'UNFURNISHED'))
);

CREATE INDEX IF NOT EXISTS attribute_category_ix
    ON dw.attribute(attribute_category_cd);
CREATE INDEX IF NOT EXISTS attribute_source_attribute_ix
    ON dw.attribute_source(attribute_ky);
CREATE INDEX IF NOT EXISTS lstng_attribute_value_lstng_ix
    ON dw.lstng_attribute_value(lstng_ky);
CREATE INDEX IF NOT EXISTS lstng_attribute_value_attribute_ix
    ON dw.lstng_attribute_value(attribute_ky);
CREATE INDEX IF NOT EXISTS lstng_attribute_value_option_ix
    ON dw.lstng_attribute_value(attribute_option_ky)
    WHERE attribute_option_ky IS NOT NULL;

CREATE INDEX IF NOT EXISTS lstng_search_attribute_beachfront_ix
    ON dw.lstng_search_attribute(lstng_ky) WHERE beachfront_fl IS TRUE;
CREATE INDEX IF NOT EXISTS lstng_search_attribute_oceanfront_ix
    ON dw.lstng_search_attribute(lstng_ky) WHERE oceanfront_fl IS TRUE;
CREATE INDEX IF NOT EXISTS lstng_search_attribute_pet_ix
    ON dw.lstng_search_attribute(lstng_ky) WHERE pet_friendly_fl IS TRUE;
CREATE INDEX IF NOT EXISTS lstng_search_attribute_pool_ix
    ON dw.lstng_search_attribute(lstng_ky) WHERE pool_fl IS TRUE;
CREATE INDEX IF NOT EXISTS lstng_search_attribute_elevator_ix
    ON dw.lstng_search_attribute(lstng_ky) WHERE elevator_fl IS TRUE;
CREATE INDEX IF NOT EXISTS lstng_search_attribute_parking_ix
    ON dw.lstng_search_attribute(lstng_ky) WHERE parking_fl IS TRUE;

CREATE OR REPLACE VIEW dw.v_lstng_attribute_detail AS
SELECT
    lav.lstng_attribute_value_ky,
    lav.lstng_ky,
    l.lstng_nb,
    a.attribute_category_cd,
    a.attribute_cd,
    a.attribute_nm,
    a.attribute_data_type_cd,
    ao.attribute_option_cd,
    ao.attribute_option_nm,
    lav.value_boolean_fl,
    lav.value_number_nb,
    lav.value_amount_nb,
    lav.value_text_tx,
    lav.value_date_dt,
    lav.raw_value_tx,
    s.source_path_tx,
    lav.source_batch_number_tx,
    lav.load_dt,
    lav.update_dt
FROM dw.lstng_attribute_value lav
JOIN dw.lstng l ON l.lstng_ky = lav.lstng_ky
JOIN dw.attribute a ON a.attribute_ky = lav.attribute_ky
JOIN dw.attribute_source s ON s.attribute_source_ky = lav.attribute_source_ky
LEFT JOIN dw.attribute_option ao ON ao.attribute_option_ky = lav.attribute_option_ky;

INSERT INTO dw.attribute_data_type_lu
(attribute_data_type_cd, attribute_data_type_nm, attribute_data_type_ds)
VALUES
    ('BOOLEAN', 'Boolean', 'Explicit true, false, or unknown.'),
    ('NUMBER',  'Number',  'General numeric value.'),
    ('AMOUNT',  'Amount',  'Currency or monetary amount.'),
    ('DATE',    'Date',    'Calendar date.'),
    ('TEXT',    'Text',    'Free or semi-structured text.'),
    ('OPTION',  'Option',  'Controlled categorical value.')
ON CONFLICT (attribute_data_type_cd) DO UPDATE SET
    attribute_data_type_nm = EXCLUDED.attribute_data_type_nm,
    attribute_data_type_ds = EXCLUDED.attribute_data_type_ds,
    active_fl = true;

INSERT INTO dw.attribute_unit_lu
(attribute_unit_cd, attribute_unit_nm, attribute_unit_ds)
VALUES
    ('MXN', 'Mexican pesos', 'Mexican peso amount.'),
    ('USD', 'US dollars', 'United States dollar amount.'),
    ('M', 'Meters', 'Linear meters.'),
    ('M2', 'Square meters', 'Area in square meters.'),
    ('FT2', 'Square feet', 'Area in square feet.'),
    ('COUNT', 'Count', 'Whole or fractional count.')
ON CONFLICT (attribute_unit_cd) DO UPDATE SET
    attribute_unit_nm = EXCLUDED.attribute_unit_nm,
    attribute_unit_ds = EXCLUDED.attribute_unit_ds,
    active_fl = true;

COMMIT;
